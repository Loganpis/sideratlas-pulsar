#!/usr/bin/env python3
"""Numerically evolve the field, then assess convergence before photon claims."""
from pathlib import Path
import sys,os,json,time,hashlib
from dataclasses import asdict,replace
import numpy as np
ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'src'))
os.environ.setdefault('MPLCONFIGDIR',str(ROOT/'.mpl-cache'))
from pulsar.plasma import PlasmaConfig,Magnetosphere,cross,parallel_component
from scipy.interpolate import RegularGridInterpolator

OUT=ROOT/'outputs'/'plasma-upgrade'


def dump(path,obj):
    def encode(a):
        if isinstance(a,np.ndarray): return a.tolist()
        if isinstance(a,np.generic): return a.item()
        raise TypeError(type(a).__name__)
    path.write_text(json.dumps(obj,indent=2,default=encode,allow_nan=False)+'\n')


def spherical_flux(axis,e,b,radii=(1.,1.5,2.)):
    mu,w=np.polynomial.legendre.leggauss(32); phi=np.arange(96)*2*np.pi/96
    directions=np.stack(np.broadcast_arrays(np.sqrt(1-mu[:,None]**2)*np.cos(phi),
                    np.sqrt(1-mu[:,None]**2)*np.sin(phi),mu[:,None]),axis=-1)
    flux=cross(e,b).transpose(1,2,3,0)
    interp=RegularGridInterpolator((axis,axis,axis),flux,bounds_error=True)
    out=[]
    for radius in radii:
        value=interp(radius*directions)
        out.append(float(np.sum(np.sum(value*directions,axis=-1)*w[:,None])*2*np.pi/96*radius**2))
    return out


def run(config,rotations=3):
    label=('resistive' if config.plasma else 'vacuum')+f'-n{config.n}'
    file=OUT/(label+'.npz'); track=OUT/(label+'-history.json')
    if file.exists() and track.exists():
        saved=np.load(file)
        if 'generation_source_sha256' in saved:
            generated=str(saved['generation_source_sha256'])
            current=hashlib.sha256((ROOT/'src/pulsar/plasma.py').read_bytes()).hexdigest()
            if generated!=current:
                raise ValueError(f'{file.name} was generated by different solver code; preserve it and run into a new output directory')
        diagnostics=json.loads(str(saved['diagnostics']))
        # An early diagnostic version reported a hypothetical plasma current
        # in vacuum mode. Reject that cached run so all saved diagnostics
        # describe the equations actually evolved.
        vacuum_diagnostics_ok=(config.plasma or
            (diagnostics['current_norm_active_domain']==0 and diagnostics['ohmic_power_active_domain']==0))
        if (json.loads(str(saved['config']))==asdict(config)
                and float(saved['time'])>=rotations*2*np.pi and vacuum_diagnostics_ok):
            print('Reusing completed '+label,flush=True)
            return file,json.loads(track.read_text())
    s=Magnetosphere(config); history=[]; start=time.monotonic()
    end=rotations*2*np.pi; interval=max(1,round(.15*2*np.pi/(s.h*config.courant)))
    while s.time<end:
        s.step(min(s.h*config.courant,end-s.time))
        if s.step_number%interval==0 or s.time>=end:
            d=s.diagnostics(); d['poynting_flux_r_1_1p5_2']=spherical_flux(s.axis,s.e,s.b)
            history.append(d)
            print(label,f't/P={s.time/(2*np.pi):.2f}, L(1.5)={d["poynting_flux_r_1_1p5_2"][1]:.4f}, divB={d["divB_relative"]:.2g}, elapsed={time.monotonic()-start:.0f}s',flush=True)
            dump(track,history)
        # No convergence is inferred from a visually rotating snapshot.
    s.save(file); return file,history


def compare_fields(low,high):
    lo,hi=np.load(low),np.load(high)
    axis=hi['axis']; x=np.array(np.meshgrid(axis,axis,axis,indexing='ij'))
    r=np.sqrt(np.sum(x*x,axis=0)); mask=(r>.8)&(r<2.4)
    pts=x[:,mask].T
    result={}
    for key in ('e','b'):
        interp=RegularGridInterpolator((lo['axis'],)*3,lo[key].transpose(1,2,3,0))
        a=interp(pts); b=hi[key][:,mask].T
        result[key+'_relative_L2']=float(np.linalg.norm(a-b)/np.linalg.norm(b))
    return result


def figures(snapshot,histories):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    d=np.load(snapshot); c=json.loads(str(d['config'])); e,b,axis=d['e'],d['b'],d['axis']
    n=len(axis); j=n//2
    ep=parallel_component(e,b); r=np.sqrt(np.sum(np.array(np.meshgrid(axis,axis,axis,indexing='ij'))**2,axis=0))
    outer=.5*(1+np.tanh((r-1)/c['conductivity_transition']))
    kappa=c['conductivity_inside']*(1-outer)+c['conductivity_outside']*outer
    q=kappa*np.sum(ep*ep,axis=0)
    plt.rcParams.update({'font.family':'STIXGeneral','mathtext.fontset':'stix','font.size':11})
    fig,axes=plt.subplots(1,3,figsize=(15,5))
    extent=(axis[0],axis[-1],axis[0],axis[-1])
    for ax,arr,title in zip(axes[:2],(np.log10(np.maximum(np.linalg.norm(b[:, :,j,:],axis=0),1e-5)),
                                    np.log10(np.maximum(q[:,j,:],1e-7))),
                               ('Evolved magnetic field — meridional slice',r'Calculated dissipation $\kappa E_\parallel^2$')):
        im=ax.imshow(arr.T,origin='lower',extent=extent,cmap='magma',vmin=(-2 if ax is axes[0] else -5),vmax=(1.5 if ax is axes[0] else 1))
        ax.add_patch(plt.Circle((0,0),c['star_radius'],color='#a0a0a0',zorder=4))
        ax.axvline(-1,color='white',ls='--',lw=.8); ax.axvline(1,color='white',ls='--',lw=.8)
        ax.set(xlim=(-2.6,2.6),ylim=(-2.6,2.6),xlabel=r'$x/R_{\rm LC}$',ylabel=r'$z/R_{\rm LC}$',title=title)
        fig.colorbar(im,ax=ax,shrink=.75,label=r'$\log_{10}$ (simulation units)')
    # These are projected vectors in a slice, not complete 3-D field lines.
    axes[0].streamplot(axis,axis,b[0,:,j,:].T,b[2,:,j,:].T,color='#ffffff99',density=.65,linewidth=.5,arrowsize=.6)
    for name,h in histories.items():
        axes[2].plot([v['time']/(2*np.pi) for v in h],
                     [v['poynting_flux_r_1_1p5_2'][1] for v in h],label=name)
    axes[2].set(xlabel='Time / rotation period',ylabel=r'Poynting flux at $1.5R_{\rm LC}$',title='Time evolution and resolution')
    axes[2].legend(fontsize=9); axes[2].spines[['top','right']].set_visible(False)
    fig.suptitle('@sideratlas / NO.002 — numerical plasma-field prototype',fontsize=18)
    fig.text(.5,.018,'Dashed lines: light cylinder · Grey disk: enlarged numerical star · Dissipation is not an observed visible colour',ha='center',fontsize=10)
    fig.tight_layout(rect=(0,.04,1,.94)); fig.savefig(OUT/'evolved-fields.png',dpi=180)
    fig.savefig(OUT/'evolved-fields.pdf'); plt.close(fig)


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    config=PlasmaConfig()
    protocol={'config':asdict(config),'resolutions':[48,64,96],'rotations':3,
              'model':'Numerical resistive Maxwell with prescribed conductivity',
              'use':'Field verification and resolution study; not a Vela fit',
              'earlier_reserved_bands':'Now development data after model redesign; no new blind validation claimed',
              'field_relative_L2_target':.10,'poynting_refinement_target':.10}
    dump(OUT/'protocol.json',protocol)
    histories={}; paths={}
    for n in protocol['resolutions']:
        path,h=run(replace(config,n=n)); paths[n]=path; histories[f'Plasma {n}³']=h
    vacuum,vh=run(replace(config,n=64,plasma=False,filter_strength=.02))
    histories['Vacuum 64³']=vh
    comparisons={f'{a}_to_{b}':compare_fields(paths[a],paths[b]) for a,b in ((48,64),(64,96))}
    fluxes={}
    for name,h in histories.items():
        last=np.array([v['poynting_flux_r_1_1p5_2'] for v in h if v['time']>4*np.pi])
        fluxes[name]={'last_rotation_mean':last.mean(axis=0),'last_rotation_relative_std':last.std(axis=0)/np.maximum(np.abs(last.mean(axis=0)),1e-20)}
    fine=fluxes['Plasma 96³']['last_rotation_mean']; coarse=fluxes['Plasma 64³']['last_rotation_mean']
    flux_change=np.abs(fine-coarse)/np.maximum(np.abs(fine),1e-20)
    theory=8*np.pi/3*np.sin(np.deg2rad(config.inclination_deg))**2
    result={
        'config':asdict(config),'field_comparisons':comparisons,'poynting':fluxes,
        'poynting_relative_change_64_to_96':flux_change,
        'vacuum_point_dipole_reference':theory,
        'vacuum_64_relative_deviation_at_r1p5':float(abs(fluxes['Vacuum 64³']['last_rotation_mean'][1]-theory)/theory),
        'field_refinement_passed':max(comparisons['64_to_96'].values())<.10,
        'flux_refinement_passed':bool(np.max(flux_change)<.10),
        'validated_for_Vela':False,
        'emission_release_allowed':False,
        'limitations':['Conductivity closure replaces kinetic pair physics','Enlarged numerical star',
                       'Second-order Cartesian mesh and explicit numerical filtering',
                       'Sponge is not a demonstrated reflection-free boundary',
                       'No particle injection or pitch distribution solved by this field model'],
        'snapshot_provenance':{
            p.name:{'snapshot_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),
                    'generation_source_sha256':str(np.load(p)['generation_source_sha256']) if 'generation_source_sha256' in np.load(p) else None}
            for p in [*paths.values(),vacuum]},
        'provenance_note':'Legacy snapshots lack generation-source fingerprints; null means unknown. Analysis hashes below must not be attributed to their generation.',
        'analysis_source_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [ROOT/'run_plasma_upgrade.py',ROOT/'src/pulsar/plasma.py']}}
    dump(OUT/'field-validation.json',result); figures(paths[96],histories)
    print(json.dumps(result,default=lambda x:x.tolist() if isinstance(x,np.ndarray) else bool(x),indent=2),flush=True)


if __name__=='__main__': main()
